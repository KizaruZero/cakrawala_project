# -*- coding: utf-8 -*-
import re
from datetime import datetime

from num2words import num2words

from odoo import api, fields, models, _
from odoo.exceptions import UserError
from odoo.tools import format_date

from .billing_engine_invoice import _LICENSE_PLATE, _without_rpc_description_prefix


class AccountMove(models.Model):
    _inherit = 'account.move'

    # Compatibility for databases restored from a newer Odoo 19 revision.
    # The newer account.move form references this field, while older local
    # Odoo 19 sources only provide is_draft_duplicated_ref_ids.
    is_exact_move_duplicate = fields.Boolean(
        compute='_compute_is_draft_duplicated_ref_ids',
    )

    active = fields.Boolean(default=True, tracking=True)

    is_et_penalty_invoice = fields.Boolean(
        string='Invoice Penalti ET',
        default=False,
        copy=False,
        help='Menandakan invoice ini merupakan Invoice Penalti hasil Request Early Termination Rental Order.',
    )

    x_is_rental_invoice = fields.Boolean(
        string='Is Rental Invoice',
        default=False,
        help='Flag to identify invoices auto-generated by the Rental Invoicing system.'
    )

    x_rental_period_start = fields.Date(
        string='Rental Period Start',
        help='Start date of the rental period covered by this invoice.'
    )

    x_rental_period_end = fields.Date(
        string='Rental Period End',
        help='End date of the rental period covered by this invoice.'
    )

    x_rental_delivery_date = fields.Date(
        string='Rental Delivery Date',
        help='Actual delivery date group for non-consolidated invoices.'
    )

    # --- Signoff Fields ---
    signoff_name = fields.Char(string='Signoff Name', tracking=True)
    signoff_position = fields.Char(string='Signoff Position', tracking=True)

    def _customer_invoice_print_date(self, value):
        """Explicit English date format, independent of the recipient's locale."""
        self.ensure_one()
        return format_date(self.env, value, lang_code='en_US', date_format='MMM d, yyyy') if value else ''

    def _customer_invoice_print_fees(self):
        """Print-only classification; never change accounting bases or taxes."""
        self.ensure_one()
        return self.invoice_line_ids.filtered(lambda line: line.display_type == 'product' and (
            line.x_is_stamp_duty or re.search(r'\bbiaya\b', line.name or '', re.IGNORECASE)
        ))

    def _customer_invoice_print_dpp(self):
        self.ensure_one()
        return self.currency_id.round(
            self.amount_untaxed - sum(self._customer_invoice_print_fees().mapped('price_subtotal'))
        )

    def _customer_invoice_print_groups(self, lines):
        """Group visible descriptions, retaining real lines and section/note order.

        Values are summed from rounded accounting lines, not recalculated with
        representative taxes. Different plates/date ranges remain separate.
        Native collapsed sections retain their own composition behaviour.
        """
        self.ensure_one()
        groups, descriptions = {}, {}
        for line in lines:
            if line.display_type != 'product' or line.collapse_composition or line.collapse_prices:
                descriptions = {}
                continue
            if line.x_is_stamp_duty:
                continue  # Already disclosed separately in totals.
            description = line._rental_invoice_print_description()
            group = descriptions.get(description)
            if group is None:
                group = descriptions[description] = groups[line.id] = {
                    'description': description, 'quantity': 0.0,
                    'price_subtotal': 0.0, 'price_total': 0.0,
                    'gross': 0.0, 'net': 0.0, 'price_unit': line.price_unit,
                }
            group['quantity'] += line.quantity
            group['price_subtotal'] += line.price_subtotal
            group['price_total'] += line.price_total
            group['gross'] += line.quantity * line.price_unit
            group['net'] += line.quantity * line.price_unit * (1 - line.discount / 100)
        for group in groups.values():
            # A weighted unit price/discount also reconciles descriptions whose
            # source lines have different rates. Zero-quantity adjustments keep
            # the first rate and their exact summed Amount.
            if group['quantity']:
                group['price_unit'] = group['gross'] / group['quantity']
            group['discount'] = 100 * (1 - group['net'] / group['gross']) if group['gross'] else 0.0
        return groups

    def _invoice_amount_words_indonesian(self):
        self.ensure_one()
        amount = self.currency_id.round(self.amount_total)
        integer, _, fraction = f'{abs(amount):.{self.currency_id.decimal_places}f}'.partition('.')
        words = num2words(int(integer), lang='id')
        if amount < 0:
            words = 'minus ' + words
        unit = 'rupiah' if self.currency_id.name == 'IDR' else self.currency_id.currency_unit_label
        words += ' ' + (unit or self.currency_id.name)
        if int(fraction or 0):
            words += ' dan ' + num2words(int(fraction), lang='id') + ' ' + (
                'sen' if self.currency_id.name == 'IDR' else self.currency_id.currency_subunit_label
            )
        return words[:1].upper() + words[1:]

    @api.depends('duplicated_ref_ids')
    def _compute_is_draft_duplicated_ref_ids(self):
        super()._compute_is_draft_duplicated_ref_ids()
        for move in self:
            move.is_exact_move_duplicate = any(
                move.ref
                and move.ref == duplicate.ref
                and move.move_type == duplicate.move_type
                and move.partner_id == duplicate.partner_id
                and move.invoice_date == duplicate.invoice_date
                and move.amount_total == duplicate.amount_total
                and move.is_purchase_document()
                for duplicate in move.duplicated_ref_ids
            )

    def _update_related_rental_tracking(self):
        for move in self:
            if move.x_is_rental_invoice or move.invoice_origin:
                sale_lines = move.line_ids.sale_line_ids
                if sale_lines:
                    sale_lines._update_invoice_tracking()

    def _post(self, soft=True):
        res = super(AccountMove, self)._post(soft=soft)
        self._update_related_rental_tracking()
        return res

    def button_draft(self):
        res = super(AccountMove, self).button_draft()
        self._update_related_rental_tracking()
        return res

    def button_cancel(self):
        res = super(AccountMove, self).button_cancel()
        self._update_related_rental_tracking()
        return res

    def unlink(self):
        for record in self:
            if record.state not in ('draft', 'cancel'):
                raise UserError(_("You can only delete invoices in Draft or Cancelled status. For posted invoices, please archive them instead."))
        sale_lines = self.line_ids.sale_line_ids
        res = super(AccountMove, self).unlink()
        if sale_lines:
            sale_lines._update_invoice_tracking()
        return res


class AccountMoveLine(models.Model):
    _inherit = 'account.move.line'

    x_is_stamp_duty = fields.Boolean(
        string='Stamp Duty', copy=True,
        help='An actual accounting charge, shown separately in invoice totals.',
    )

    x_plate_number = fields.Char(
        string='Plate Number/Asset Number',
        help='Vehicle plate number or asset number associated with this invoice line.'
    )

    x_billing_month = fields.Char(
        string='Billing Month',
        help='Billing month indicator (e.g., "1 of 12").'
    )
    is_et_penalty_invoice = fields.Boolean(
        related='move_id.is_et_penalty_invoice',
        string='Is ET Penalty Invoice',
        readonly=True,
    )

    def write(self, vals):
        if 'price_unit' in vals and not self.env.context.get('allow_et_penalty_price_change'):
            for line in self:
                if line.move_id.is_et_penalty_invoice:
                    if line.price_unit != vals['price_unit']:
                        raise UserError(_('Harga (Price) pada Invoice Penalti Early Termination tidak dapat dirubah karena sudah diapprove oleh Direktur.'))
        return super().write(vals)

    def _rental_invoice_print_description(self):
        """Format legacy printouts too, without rewriting posted journal items."""
        self.ensure_one()
        if not (self.move_id.x_is_rental_invoice or self.sale_line_ids.order_id.filtered('is_rental_order')):
            return self.name or ''
        text = _without_rpc_description_prefix(self.name)
        plates = [self.x_plate_number] if _LICENSE_PLATE.fullmatch(self.x_plate_number or '') else []
        if not plates:
            plates = [line._rental_invoice_license_plate() for line in self.sale_line_ids]
            plates = list(dict.fromkeys(plate for plate in plates if plate))
        result = []
        for paragraph in text.splitlines():
            if re.fullmatch(r'\s*Unit plate No\s*:.*', paragraph, flags=re.IGNORECASE):
                result.append(', '.join(plates) or '-')
                continue
            # Older rental invoices also used "16th September 2026".
            match = re.fullmatch(r'\s*(.+?)\s+-\s+(.+?)\s*', paragraph)
            if match:
                dates = []
                for value in match.groups():
                    value = re.sub(r'(?<=\d)(?:st|nd|rd|th)\b', '', value, flags=re.IGNORECASE)
                    for pattern in ('%Y-%m-%d', '%d-%m-%Y', '%d %B %Y', '%d %b %Y'):
                        try:
                            dates.append(datetime.strptime(value, pattern).date())
                            break
                        except ValueError:
                            continue
                if len(dates) == 2:
                    paragraph = ' - '.join(self.move_id._customer_invoice_print_date(value) for value in dates)
            result.append(paragraph)
        return '\n'.join(result)
